"""The Python filter must give exactly the TypeScript result (tests/vectors.json,
regenerated by `npm run vectors`)."""
import json
from pathlib import Path

import pytest

from exaequo_map import can_enter, filter_for_viewer

DATA = json.loads((Path(__file__).parent / "vectors.json").read_text("utf-8"))
STATIC = DATA["staticMap"]
FILTER_CASES = [c for c in DATA["cases"] if "expected" in c]
ENTER_CASES = [c for c in DATA["cases"] if "canEnter" in c]


def roundtrip(o):
    return json.loads(json.dumps(o))


@pytest.mark.parametrize("case", FILTER_CASES, ids=lambda c: f"p{c['progress']}-{c['viewer']}-gm{c['gm']}")
def test_filter_matches_typescript(case):
    got = roundtrip(filter_for_viewer(STATIC, case["state"], case["viewer"], gm=case["gm"]))
    assert got == case["expected"]


@pytest.mark.parametrize("case", ENTER_CASES, ids=lambda c: f"p{c['progress']}")
def test_can_enter_matches_typescript(case):
    for rid, expected in case["canEnter"]:
        assert can_enter(STATIC, case["state"], rid) is expected, rid


def test_viewer_none_requires_gm():
    with pytest.raises(PermissionError):
        filter_for_viewer(STATIC, FILTER_CASES[0]["state"], None)


def test_player_view_has_no_secrets():
    for c in FILTER_CASES:
        if c["gm"]:
            continue
        v = filter_for_viewer(STATIC, c["state"], c["viewer"])
        assert "gm" not in v
        assert all("value" not in d for d in v["details"].values())
        assert set(v["known"]) <= {c["viewer"]}
        vis = set(v["visible"])
        assert all(int(pid) in vis for pid in v["provinces"])
